internal static class ProtocolGeneratorTests
{
    internal static void Run()
    {
        foreach (var (first, second, expected) in new[]
        {
            ("JSONRPCResponse", "JSONRPCMessage", "JSONRPCResponseMessage"),
            ("McpBooleanSchema", "McpPrimitiveSchema", "McpBooleanPrimitiveSchema"),
            ("Version2Event", "Version2Notice", "Version2EventNotice"),
            ("Foo", "Food", "FooFood"),
        })
            Check(ProtocolGenerator.CombineTypeNames(first, second) == expected, "shared name words");
        Check(ProtocolGenerator.NestedTypeName("GranularAskForApproval", "Granular", JsonNode.Parse("{\"type\":\"object\"}"))
            == "GranularAskForApprovalGranular", "nested owner context");
        Check(ProtocolGenerator.VariantTypeName("Result", "Result") == "ResultVariant", "variant base collision");
        Check(ProtocolGenerator.VariantTypeName("McpElicitationUntitledSingleSelectEnumSchema", "McpElicitationSingleSelectEnumSchema", true)
            == "McpElicitationUntitledSingleSelectEnumSchemaVariant", "wrapped variant collision");

        var selectionDefinitions = """
            {"Reply":{"type":"object","properties":{"value":{"$ref":"#/definitions/Choice"},"unused":{"type":"string"}},"required":["value","unused"]},
             "Choice":{"oneOf":[
               {"title":"FirstChoice","type":"object","properties":{"type":{"type":"string","enum":["first"]},"answer":{"type":"string"},"extra":{"type":"string"}},"required":["type","answer","extra"]},
               {"title":"SecondChoice","type":"object","properties":{"type":{"type":"string","enum":["second"]}},"required":["type"]}]},
             "Unrelated":{"type":"object","properties":{"x":{"type":"string"}}}}
            """;
        var selected = Generate(selectionDefinitions, """
            {"roots":["Reply"],"types":{"Reply":["value"],"Choice":{"variants":{"first":["answer"]}}}}
            """);
        Check(selected.Keys.ToHashSet(StringComparer.Ordinal).SetEquals(["Reply.g.cs", "Choice.g.cs", "FirstChoice.g.cs", "manifest.json"]),
            "selected output closure");
        Check(selected["Reply.g.cs"].Contains("[JsonPropertyName(\"value\")]", StringComparison.Ordinal)
            && !selected["Reply.g.cs"].Contains("Unused", StringComparison.Ordinal)
            && !selected["FirstChoice.g.cs"].Contains("Extra", StringComparison.Ordinal)
            && !selected["Choice.g.cs"].Contains("SecondChoice", StringComparison.Ordinal), "selected fields and variants");
        var referenceDefinitions = """
            {"Reply":{"type":"object","properties":{"child":{"$ref":"#/definitions/Child"}}},
             "Child":{"type":"object","properties":{"text":{"type":"string"}}}}
            """;
        ExpectFailure(() => Generate(referenceDefinitions, """{"roots":["Reply"],"types":{"Reply":["missing"]}}"""),
            "Unknown selected field");
        ExpectFailure(() => Generate(referenceDefinitions, """{"roots":["Reply"],"types":{"Reply":["child"]}}"""),
            "lacks a selection: Child");
        ExpectFailure(() => Generate("""
            {"Reply":{"type":"object","additionalProperties":false,"properties":{"kept":{"type":"string"},"dropped":{"type":"string"}}}}
            """, """{"roots":["Reply"],"types":{"Reply":["kept"]}}"""),
            "Closed Codex object needs all fields");

        var collisionDefinitions = """
            {"AcceptWithPolicyDetails":{"type":"object","properties":{"original":{"type":"boolean"}}},
             "FirstAcceptWithPolicyDecision":{"type":"object","properties":{"acceptWithPolicy":{"type":"object","properties":{"value":{"type":"string"}}}}},
             "SecondAcceptWithPolicyDecision":{"type":"object","properties":{"acceptWithPolicy":{"type":"object","properties":{"value":{"type":"integer"}}}}}}
            """;
        var collisions = Generate(collisionDefinitions);
        Check(collisions["FirstAcceptWithPolicyDecision.g.cs"].Contains("AcceptWithPolicyDetails2? AcceptWithPolicy", StringComparison.Ordinal)
            && collisions["SecondAcceptWithPolicyDecision.g.cs"].Contains("AcceptWithPolicyDetails3? AcceptWithPolicy", StringComparison.Ordinal),
            "anonymous type collisions");
        var variants = Generate("""
            {"FirstResult":{"oneOf":[{"title":"SharedVariant","type":"object","properties":{"value":{"type":"string"}},"required":["value"]}]},
             "SecondResult":{"oneOf":[{"title":"SharedVariant","type":"object","properties":{"value":{"type":"string"}},"required":["value"]}]}}
            """);
        Check(variants["SharedVariant.g.cs"].Contains("class SharedVariant : FirstResult", StringComparison.Ordinal)
            && variants["SharedVariant2.g.cs"].Contains("class SharedVariant2 : SecondResult", StringComparison.Ordinal),
            "variants retain their base class");
    }

    private static Dictionary<string, string> Generate(string definitions, string? selection = null)
    {
        var directory = Path.Combine(Path.GetTempPath(), "goblin-protocol-generator-" + Guid.NewGuid().ToString("N"));
        Directory.CreateDirectory(directory);
        try
        {
            File.WriteAllText(Path.Combine(directory, "codex_app_server_protocol.schemas.json"),
                "{\"definitions\":" + definitions + "}");
            return new ProtocolGenerator(directory, selection).Generate();
        }
        finally { Directory.Delete(directory, true); }
    }

    private static void Check(bool condition, string message)
    {
        if (!condition) throw new InvalidOperationException("Generator test failed: " + message);
    }

    private static void ExpectFailure(Action action, string message)
    {
        try { action(); }
        catch (InvalidOperationException error) when (error.Message.Contains(message, StringComparison.Ordinal)) { return; }
        throw new InvalidOperationException("Generator test failed: expected " + message);
    }
