-- Initial schema for an empty database. Apply with the schema administrator;
-- the application cannot run DDL. All tables live directly in public.

-- Goblin-owned table IDs and their references use bigint uniformly. Runtime
-- sessions are opaque references; Wolverine's vendor-owned keys remain below.
CREATE TABLE public.connection (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    runtime text NOT NULL,
    name text NOT NULL,
    availability text NOT NULL DEFAULT 'Disconnected',
    account_signature text,
    auth_generation bigint NOT NULL DEFAULT 0,
    changed_at timestamptz NOT NULL DEFAULT now()
);
-- A catalog belongs to one account generation and one installed Codex CLI
-- revision. A failed refresh preserves the last successful catalog.
CREATE TABLE public.connection_model_catalog (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    connection_id bigint NOT NULL UNIQUE REFERENCES public.connection(id),
    auth_generation bigint NOT NULL,
    executable_stamp text NOT NULL,
    catalog jsonb,
    fetched_at timestamptz,
    retry_after timestamptz,
    refresh_failed boolean NOT NULL DEFAULT false
);
CREATE TABLE public.agent (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL,
    connection_id bigint NOT NULL REFERENCES public.connection(id),
    model text
);
