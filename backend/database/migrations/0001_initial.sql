CREATE TABLE public.work_item (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    objective text NOT NULL,
    state jsonb NOT NULL,
    version bigint NOT NULL DEFAULT 1 CHECK (version > 0),
    status text NOT NULL DEFAULT 'Ready',
    agent_id bigint REFERENCES public.agent(id),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX work_item_updated ON public.work_item(updated_at DESC, id);

-- A connector token establishes identity. Only this installation's owner can
-- share a Work item; a result grant pins one approved attempt, never future output.
CREATE TABLE public.chatgpt_work_grant (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    issuer varchar(2048) NOT NULL,
    subject varchar(256) NOT NULL CHECK (length(btrim(subject)) > 0),
    resource varchar(2048) NOT NULL,
    work_id bigint NOT NULL REFERENCES public.work_item(id),
    result_attempt_id bigint,
    approved_at timestamptz NOT NULL DEFAULT now(),
    expires_at timestamptz NOT NULL,
    revoked_at timestamptz,
    CHECK (expires_at > approved_at AND expires_at <= approved_at + interval '7 days'),
    CHECK (revoked_at IS NULL OR revoked_at >= approved_at)
);
CREATE UNIQUE INDEX chatgpt_work_grant_current ON public.chatgpt_work_grant(issuer, subject, resource, work_id)
    WHERE revoked_at IS NULL;
CREATE TABLE public.chatgpt_grant_event (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    grant_id bigint NOT NULL REFERENCES public.chatgpt_work_grant(id),
    action text NOT NULL CHECK (action IN ('approved', 'revoked')),
    actor text NOT NULL CHECK (actor = 'local-owner'),
    occurred_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX chatgpt_grant_event_grant ON public.chatgpt_grant_event(grant_id, id);

-- Projection used for capacity, ownership, and recovery queries. The immutable
-- attempt data and ordered product history also live in the Work snapshot.
CREATE TABLE public.execution_attempt (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    work_id bigint NOT NULL REFERENCES public.work_item(id),
    agent_id bigint NOT NULL REFERENCES public.agent(id),
    connection_id bigint NOT NULL REFERENCES public.connection(id),
    runtime text NOT NULL,
    status text NOT NULL,
    owner_id bigint,
    environment_reference text,
    queued_at timestamptz NOT NULL,
    updated_at timestamptz NOT NULL,
    -- Cleanup is durable work for the host, never permission to execute again.
    cleanup_pending boolean NOT NULL DEFAULT false,
    cleanup_failed boolean NOT NULL DEFAULT false
);
CREATE INDEX execution_attempt_recovery ON public.execution_attempt(status, updated_at);
