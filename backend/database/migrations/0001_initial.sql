-- Successful setup observations are scoped to a connected repository. Keep
-- branch/configuration variants and execution provenance rather than a single
-- mutable recipe. The checkpoint fences the observation to a saved turn.
CREATE TABLE public.repository_setup_memory (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    repository_id bigint NOT NULL REFERENCES public.github_repository(id),
    github_connection_id bigint NOT NULL REFERENCES public.github_connection(id),
    account_id text NOT NULL,
    checkpoint_id bigint NOT NULL REFERENCES public.workspace_checkpoint(id),
    work_id bigint NOT NULL REFERENCES public.work_item(id),
    attempt_id bigint NOT NULL REFERENCES public.execution_attempt(id),
    turn_number integer NOT NULL CHECK (turn_number > 0),
    topic text NOT NULL CHECK (length(topic) BETWEEN 1 AND 80),
    environment text NOT NULL CHECK (length(environment) BETWEEN 1 AND 1000),
    fingerprint text NOT NULL CHECK (length(fingerprint) = 64),
    observation jsonb NOT NULL CHECK (octet_length(observation::text) <= 65536),
    verified_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (attempt_id, turn_number, topic)
);
CREATE INDEX repository_setup_recall ON public.repository_setup_memory
    (github_connection_id, account_id, repository_id, verified_at DESC);

