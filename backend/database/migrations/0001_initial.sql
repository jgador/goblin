CREATE TABLE public.workspace_checkpoint (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    work_id bigint NOT NULL REFERENCES public.work_item(id),
    attempt_id bigint NOT NULL REFERENCES public.execution_attempt(id),
    turn_number integer NOT NULL,
    workspace_number integer NOT NULL,
